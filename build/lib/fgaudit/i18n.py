def localize_notice(n: Notice, lang: str) -> None:
    t = NOTICES.get(n.code)
    if t is None:
        n.text = n.code
        return
    s = t.get(lang, t["en"])
    try:
        n.text = s.format(**n.params)
    except (KeyError, IndexError):
        n.text = s


