def event_text(lang: str, r: Dict[str, Any]) -> str:
    de = lang == "de"
    cat, st, obj, kind = r["category"], r["state"], r["object"], r["kind"]
    c = CAT[lang].get(cat, cat)
    W = {
        "down": "down" if not de else "down",
        "up": "up",
        "fail": "failed" if not de else "fehlgeschlagen",
    }
    if cat == "interface":
        return f"{c} {obj} {W.get(st, st)}"
    if cat in ("bgp", "ospf"):
        return (f"{c} neighbor {obj} {W.get(st, st)}" if not de else f"{c}-Nachbar {obj} {W.get(st, st)}")
    if cat == "conserve":
        o = obj if not de else {"memory": "Speicher", "file descriptor": "File Descriptors"}.get(obj, obj)
        return (f"Entered conserve mode ({o})" if st == "enter" else f"Left conserve mode ({o})") if not de else \
            (f"Conserve Mode aktiviert ({o})" if st == "enter" else f"Conserve Mode beendet ({o})")
    if cat == "sdwan":
        if kind == "sla":
            return f"SD-WAN SLA {obj}" + (" down" if st == "down" else "")
        what = "link monitor" if kind == "linkmon" else ("member" if not de else "Member")
        return f"SD-WAN {what} {obj} {W.get(st, st)}" if st != "info" else f"SD-WAN {what} {obj}"
    if cat == "ipsec":
        if kind == "negotiate":
            return (f"IPsec negotiation {obj} " + ("failed" if st == "fail" else "")).strip() if not de else \
                (f"IPsec-Aushandlung {obj} " + ("fehlgeschlagen" if st == "fail" else "")).strip()
        return f"IPsec {('tunnel' if not de else 'Tunnel')} {obj} {W.get(st, st)}".strip() if st != "info" else f"IPsec {obj}"
    if cat == "ha":
        m = {
            "en": {"failover": "HA failover", "failover-fail": "HA failover failed", "state": "HA member state changed", "devfail": "HA monitored interface failed",
                   "hbdown": "HA heartbeat interface down", "up": "HA heartbeat interface up", "primary": "Device became HA primary", "hblost": "HA heartbeat packets lost",
                   "syncfail": "HA sync failed"},
            "de": {"failover": "HA-Failover", "failover-fail": "HA-Failover fehlgeschlagen", "state": "HA-Mitgliedsstatus geändert", "devfail": "Überwachtes HA-Interface ausgefallen",
                   "hbdown": "HA-Heartbeat-Interface down", "up": "HA-Heartbeat-Interface up", "primary": "Gerät wurde HA-Primary", "hblost": "HA-Heartbeat-Pakete verloren",
                   "syncfail": "HA-Synchronisierung fehlgeschlagen"},
        }[lang]
        return f"{m.get(st, 'HA ' + st)} ({obj})"
    if cat == "admin":
        if st == "loginfail":
            return f"Admin login failed: {obj}" if not de else f"Admin-Login fehlgeschlagen: {obj}"
        return f"Admin login: {obj}" if not de else f"Admin-Login: {obj}"
    if cat == "config":
        u = r.get("user") or "?"
        return f"Config changed by {u}: {obj}" if not de else f"Konfiguration geändert von {u}: {obj}"
    if cat == "system":
        return ("Device rebooted" if st == "reboot" else "Device shut down") if not de else ("Gerät neu gestartet" if st == "reboot" else "Gerät heruntergefahren")
    if cat == "routing":
        return f"Routing {obj} {st}"
    return f"{c} {obj} {st}"


