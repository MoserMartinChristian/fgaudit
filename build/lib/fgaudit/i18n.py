def _profiles(lang: str, p: Dict[str, Any]) -> str:
    prof = p.get("profiles") or {}
    if not prof:
        return ""
    parts = [f"{k}: {v[1]} -> {v[0]}" for k, v in list(prof.items())[:5]]
    if lang == "de":
        return " Security-Profile unterscheiden sich (spätere -> frühere Policy): " + "; ".join(parts) + "."
    return " Security profiles differ (later -> earlier policy): " + "; ".join(parts) + "."


def _order_note(lang: str, p: Dict[str, Any]) -> str:
    if not p.get("id_order_differs"):
        return ""
    if lang == "de":
        return f" Hinweis: Policy {p['earlier']} hat die höhere ID, steht aber weiter oben (Position {p['earlier_pos']} vor {p['later_pos']}). Es zählt die Reihenfolge, nicht die ID."
    return f" Note: policy {p['earlier']} has the higher ID but sits higher in the list (position {p['earlier_pos']} before {p['later_pos']}). Order counts, not the ID."


