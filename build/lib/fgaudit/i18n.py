def t_change(code):
    def f(lang, p):
        t = CHG.get(code) or CHG["change.other"]
        title, why, nxt = t.get(lang, t["en"])
        others = p.get("others") or []
        fmt = {
            "key": p.get("key") or p.get("path", ""),
            "obj": _chg_obj(lang, p),
            "kind": _kind(lang, p.get("kind", "modified")),
            "pol": pol(p.get("policy", ""), p.get("policy_name", "")),
            "removed": ", ".join(p.get("removed") or []),
            "added": ", ".join(p.get("added") or []),
            "risky": ", ".join(p.get("risky") or []),
            "broad": ", ".join(DIMS[lang].get(b, b) for b in (p.get("broad") or [])),
            "action": p.get("action", ""),
            "to": p.get("to", ""),
            "fields": ", ".join(p.get("fields") or []),
            "others": ", ".join(pol(o["id"], o["name"]) for o in others),
            "old_pos": p.get("old_pos", ""), "new_pos": p.get("new_pos", ""),
            "vdom": p.get("vdom", ""),
        }
        detail = why.format(**fmt)
        fields = _chg_fields(lang, p)
        if fields and not code.startswith("change.order") and code != "change.secret-not-comparable" and not (p.get("kind") == "added" and p.get("policy")):
            detail += (" Änderungen: " if lang == "de" else " Changes: ") + fields + "."
        detail += _impact(lang, p)
        if p.get("nolog"):
            detail += (" Logging ist deaktiviert." if lang == "de" else " Logging is disabled.")
        return title.format(**fmt), detail, nxt.format(**fmt)
    return f


def t_timeline(lang, p):
    tr = p["trigger"]
    txt = event_text(lang, tr)
    conf = CONF[lang][p["confidence"]]
    reasons = "; ".join(REASON[lang].get(r, r) for r in p["reasons"])
    n_follow = len(p["chain"]) + p.get("more", 0)
    if lang == "de":
        title = f"Incident {p['n']}: wahrscheinlicher Auslöser ist \"{txt}\" ({tr['device']}, {tr['time']})"
        detail = f"Vermutung, kein Beweis. Vertrauen: {conf}. Begründung: Es ist das früheste auffällige Ereignis dieses Zeitraums, {n_follow} Folgeereignis(se); {reasons}."
        if p.get("precursor"):
            pc = p["precursor"]
            detail += f" {pc['before']} s vorher: \"{event_text(lang, pc)}\". Prüf, ob diese Änderung der eigentliche Auslöser war."
        nxt = "Prüf den Auslöser zuerst (Interface-Status, Leitung, Gegenstelle) und vergleiche die Zeiten mit anderen Quellen, z. B. FortiAnalyzer oder Provider-Tickets."
    else:
        title = f"Incident {p['n']}: likely trigger is \"{txt}\" ({tr['device']}, {tr['time']})"
        detail = f"Hypothesis, not proof. Confidence: {conf}. Reasoning: it is the earliest anomalous event in this time frame, with {n_follow} follow-up event(s); {reasons}."
        if p.get("precursor"):
            pc = p["precursor"]
            detail += f" {pc['before']} s earlier: \"{event_text(lang, pc)}\". Check whether this change was the actual trigger."
        nxt = "Check the trigger first (interface status, circuit, remote peer) and compare the times with other sources such as FortiAnalyzer or provider tickets."
    return title, detail, nxt


