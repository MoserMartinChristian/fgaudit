def _ov(lang, p, title_en, title_de, why_en, why_de, next_en, next_de):
    a = f"{KIND[lang].get(p['a_kind'], p['a_kind'])} {p['a_name']} ({p['a_range']}, VDOM {p['a_vdom']})"
    b = f"{KIND[lang].get(p['b_kind'], p['b_kind'])} {p['b_name']} ({p['b_range']}, VDOM {p['b_vdom']})"
    if lang == "de":
        return (title_de.format(a=p["a_name"], b=p["b_name"]),
                f"{a} und {b} überlappen im Bereich {p['overlap']}. {why_de}", next_de)
    return (title_en.format(a=p["a_name"], b=p["b_name"]),
            f"{a} and {b} overlap in {p['overlap']}. {why_en}", next_en)


